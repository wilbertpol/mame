void explorer_nupi_device::push_fifo_word_to_nubus(u16 word)
{
	if (!m_scsi_fifo_have_pending_word)
	{
		m_scsi_fifo_pending_word = word;
		m_scsi_fifo_have_pending_word = true;
		return;
	}

	u32 const longword = swapendian_int32((u32(m_scsi_fifo_pending_word) << 16) | word);
	u32 const real_addr = m_dma_address;
	if (m_dma_mode == DMA_FIFO_TO_NUBUS)
	{
		LOGMASKED(LOG_DMA, "%s: dma -> nubus[%08x] = %08x\n", machine().describe_context(), real_addr, longword);
		nubus().space().write_dword(real_addr, longword);
	}
	else
	{
		LOGMASKED(LOG_DMA, "%s: dma (no target configured, not writing to nubus) dma_addr=%08x = %08x\n", machine().describe_context(), m_dma_address, longword);
	}
	m_dma_address += 4;
	m_scsi_fifo_have_pending_word = false;

	m_dma_count--;

	if (!m_dma_count)
		dma_transfer_complete();
}

void explorer_nupi_device::scsi_dreq_w(int state)
{
	if (!state)
		return;

	LOGMASKED(LOG_DMA, "%s: scsi_dreq_w state=%d m_dma_count=%08x\n", machine().describe_context(), state, m_dma_count);

	u32 const ctrl = m_scsibus->ctrl_r();
	bool const in = (ctrl & nscsi_device_interface::S_INP);

	if (in)
	{
		u8 const data = m_scsi->dma_r();
		if (!m_scsi_fifo_have_pending_byte)
		{
			LOGMASKED(LOG_DMA, "%s: scsi_dreq_w IN byte=%02x (pending, no word yet)\n", machine().describe_context(), data);
			m_scsi_fifo_pending_byte = data;
			m_scsi_fifo_have_pending_byte = true;
		}
		else
		{
			if (m_dma_transfer_start_pending)
			{
				m_dma_transfer_start_pos = m_fifo_in_pos & 0x7ff;
				m_dma_transfer_start_pending = false;
			}

			u16 const word = (u16(m_scsi_fifo_pending_byte) << 8) | data;
			LOGMASKED(LOG_DMA, "%s: scsi_dreq_w IN byte=%02x -> fifo[%u] = %04x\n", machine().describe_context(), data, m_fifo_in_pos & 0x7ff, word);
			fifo_push(word);
			m_scsi_fifo_have_pending_byte = false;

			dma_drain_kick();
		}
	}
	else
	{
		m_scsi->dma_w(nubus().space().read_byte(m_dma_address));
		m_dma_address++;

		if (m_dma_mode == DMA_NUBUS_TO_SCSI && ++m_dma_out_byte_phase == 4)
		{
			m_dma_out_byte_phase = 0;
			m_dma_count--;

			if (!m_dma_count)
			{
				m_mpu->set_input_line(M68K_IRQ_1, ASSERT_LINE);

				m_dma_mode = DMA_IDLE;
				m_unknown_100001 = 0;
			}
		}
	}
}


//**************************************************************************
//  Machine configuration
//**************************************************************************

void explorer_nupi_device::device_add_mconfig(machine_config &config)
{
	M68000(config, m_mpu, 40_MHz_XTAL / 4); // Image of board has a 40MHz crystal, documents mention 68000 at 10MHz.
	m_mpu->set_addrmap(AS_PROGRAM, &explorer_nupi_device::mpu_map);

	NSCSI_BUS(config, m_scsibus);
	// The unit byte in command word 0 is (unit << 3) | device, so a mass
	// storage unit's SCSI ID picks the unit numbers the software has to ask for.
	NSCSI_CONNECTOR(config, "scsibus:0", nupi_scsi_devices, "msu", false);   // units 00, 01
	NSCSI_CONNECTOR(config, "scsibus:1", nupi_scsi_devices, nullptr, false); // units 08, 09
	NSCSI_CONNECTOR(config, "scsibus:2", nupi_scsi_devices, "msu", false);   // units 10, 11
	NSCSI_CONNECTOR(config, "scsibus:3", nupi_scsi_devices, "mt3201", false); // units 18, 19

	NCR5385(config, m_scsi, 40_MHz_XTAL / 4); // clock not documented.
	m_scsibus->set_external_device(5, m_scsi);
	m_scsi->set_own_id(5);
	m_scsi->irq().set(FUNC(explorer_nupi_device::scsi_irq_w));
	m_scsi->dreq().set(FUNC(explorer_nupi_device::scsi_dreq_w));
}


