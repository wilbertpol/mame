// The input address counter is 12 bits and the self-test compares it raw, but the
// FIFO behind it is 2048 words.
void explorer_nupi_device::fifo_push(u16 word)
{
	m_fifo[m_fifo_in_pos & 0x7ff] = word;
	m_fifo_in_pos = (m_fifo_in_pos + 1) & 0x0fff;
}

TIMER_CALLBACK_MEMBER(explorer_nupi_device::dma_drain_timer_expired)
{
	if (m_dma_mode == DMA_FIFO_TO_NUBUS && m_fifo_drain_pos == (m_fifo_in_pos & 0x7ff))
		return;

	u16 const word = m_fifo[m_fifo_drain_pos];
	m_fifo_drain_pos = (m_fifo_drain_pos + 1) & 0x7ff;
	push_fifo_word_to_nubus(word);

	dma_drain_kick();
}

void explorer_nupi_device::dma_drain_kick()
{
	if (dma_draining() && !m_dma_drain_timer->enabled())
		m_dma_drain_timer->adjust(m_dma_mode == DMA_FIFO_TO_NUBUS ? attotime::from_usec(1) : attotime::from_usec(4));
}


u16 explorer_nupi_device::onboard_read16(u32 addr)
{
	u32 const local = (addr & 0x20000) ? (0x040000 | (addr & 0x3fff)) : (0x180000 | (addr & 0x0fff));
	return m_mpu->space(AS_PROGRAM).read_word(local);
}


void explorer_nupi_device::onboard_write16(u32 addr, u16 data)
{
	if (addr & 0x20000)
		return; // ROM - a transfer into it moves nothing
	m_mpu->space(AS_PROGRAM).write_word(0x180000 | (addr & 0x0fff), data);
}


void explorer_nupi_device::onboard_dma_run(bool host_group_read)
{
	if (m_dma_mode != DMA_ONBOARD)
		return;

	// Direction ($801a8) and width ($801d0 bit 15) are read live; the transfer walks the
	// address ($801c0, bits 17:2) and the count down as it goes.
	bool const to_fifo = m_dma_direction != 0;
	bool const is_16bit = BIT(m_dma_address_hi_raw, 15);

	while (m_dma_count)
	{
		// Outbound 16-bit hands the group's other half to the host port, so the
		// transfer only steps once $450000 has taken one.
		if (!to_fifo && is_16bit)
		{
			if (!host_group_read)
				return;
			host_group_read = false;
		}

		u32 const addr = u32(m_dma_address_lo_raw) << 2;
		if (to_fifo)
		{
			// Fills are always 16-bit: only the halfword at +0 is real, and it fills
			// both halves of the FIFO group (nothing else is driving the other half).
			u16 const word = onboard_read16(addr);
			fifo_push(word);
			fifo_push(word);
		}
		else
		{
			u16 const first = m_fifo[m_fifo_out_pos];
			m_fifo_out_pos = (m_fifo_out_pos + 1) & 0x7ff;
			if (is_16bit)
			{
				// The host port takes the group's other half.
				onboard_write16(addr, first);
			}
			else
			{
				u16 const second = m_fifo[m_fifo_out_pos];
				m_fifo_out_pos = (m_fifo_out_pos + 1) & 0x7ff;
				onboard_write16(addr + 2, first);
				onboard_write16(addr, second);
			}
		}

		m_dma_address_lo_raw++;
		m_dma_count--;
	}

	// Completion also raises IRQ5 when $3801ea enabled it.
	if (m_dma_irq5_enabled)
	{
		m_dma_irq5_enabled = false;
		m_mpu->set_input_line(M68K_IRQ_5, ASSERT_LINE);
	}
	dma_transfer_complete();
}


void explorer_nupi_device::dma_transfer_complete()
{
	m_mpu->set_input_line(M68K_IRQ_1, ASSERT_LINE);

	m_dma_mode = DMA_IDLE;

	m_unknown_100001 = 0;

	m_unknown_450000_holding = m_unknown_dma_803c00;

	m_dma_transfer_start_pending = true;
}


